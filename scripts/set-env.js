/**
 * Script to inject environment variables into Angular environment file at build time
 * This allows us to use environment variables from Render or other hosting platforms
 */

const fs = require('fs');
const path = require('path');

// Get environment variables with defaults
const apiUrl = process.env.API_URL || 'http://localhost:7194';
const enableAnalytics = process.env.ENABLE_ANALYTICS === 'true';
const tokenKey = process.env.TOKEN_KEY || 'mtg_auth_token';
const userKey = process.env.USER_KEY || 'mtg_auth_user';

// Build the environment configuration
const environmentConfig = `/**
 * Production environment configuration
 * This file is auto-generated by scripts/set-env.js
 * DO NOT EDIT THIS FILE MANUALLY
 */
export const environment = {
  production: true,
  apiUrl: '${apiUrl}',
  enableSSLBypass: false,
  enableAnalytics: ${enableAnalytics},
  tokenKey: '${tokenKey}',
  userKey: '${userKey}',
};
`;

// Path to the production environment file
const targetPath = path.join(__dirname, '../src/environments/environment.prod.ts');

// Write the file
fs.writeFileSync(targetPath, environmentConfig, 'utf8');

console.log('✓ Environment configuration generated successfully');
console.log(`  API URL: ${apiUrl}`);
console.log(`  Analytics: ${enableAnalytics}`);
console.log(`  Token Key: ${tokenKey}`);
console.log(`  User Key: ${userKey}`);
